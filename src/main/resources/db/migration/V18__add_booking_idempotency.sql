CREATE TABLE booking_idempotency_keys (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    idempotency_key VARCHAR(255) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    status VARCHAR(20) NOT NULL,
    attempt_token UUID NOT NULL,
    booking_id BIGINT,
    response_json TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    stale_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_booking_idempotency_user_key UNIQUE (user_id, idempotency_key),
    CONSTRAINT fk_booking_idempotency_user
        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_booking_idempotency_booking
        FOREIGN KEY (booking_id) REFERENCES bookings(id),
    CONSTRAINT ck_booking_idempotency_key CHECK (btrim(idempotency_key) <> ''),
    CONSTRAINT ck_booking_idempotency_hash CHECK (request_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_booking_idempotency_status CHECK (status IN ('IN_PROGRESS', 'COMPLETED')),
    CONSTRAINT ck_booking_idempotency_result CHECK (
        (status = 'IN_PROGRESS' AND booking_id IS NULL AND response_json IS NULL)
        OR (status = 'COMPLETED' AND booking_id IS NOT NULL AND response_json IS NOT NULL)
    ),
    CONSTRAINT ck_booking_idempotency_times CHECK (
        stale_at > created_at AND expires_at > stale_at
    )
);

CREATE INDEX idx_booking_idempotency_expires_at
    ON booking_idempotency_keys (expires_at);